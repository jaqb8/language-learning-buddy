export const TRANSLATIONS: Record<AppLocale, TranslationCatalog> = { en, pl };

export type TranslationParams = Record<string, string | number>;
export type Translator = (key: TranslationKey, params?: TranslationParams) => string;

export function normalizeAppLocale(value: unknown): AppLocale {
  return typeof value === "string" && APP_LOCALES.includes(value as AppLocale)
    ? (value as AppLocale)
    : DEFAULT_APP_LOCALE;
}

export function getIntlLocale(locale: AppLocale): "en-GB" | "pl-PL" {
  return locale === "pl" ? "pl-PL" : "en-GB";
}

export function translate(locale: AppLocale, key: TranslationKey, params: TranslationParams = {}): string {
  const message = TRANSLATIONS[locale][key];
  return Object.entries(params).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    message
  );
}

export function createTranslator(locale: AppLocale): Translator {
  return (key, params) => translate(locale, key, params);
}

interface I18nContextValue {
  locale: AppLocale;
  intlLocale: "en-GB" | "pl-PL";
  t: Translator;
}

const defaultContext: I18nContextValue = {
  locale: DEFAULT_APP_LOCALE,
  intlLocale: getIntlLocale(DEFAULT_APP_LOCALE),
  t: createTranslator(DEFAULT_APP_LOCALE),
};

const I18nContext = createContext<I18nContextValue>(defaultContext);

export function I18nProvider({ locale, children }: { locale: AppLocale; children: ReactNode }) {
  const value = useMemo<I18nContextValue>(
    () => ({ locale, intlLocale: getIntlLocale(locale), t: createTranslator(locale) }),
    [locale]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}

export function setAppLocaleCookie(locale: AppLocale): void {
  const secure = window.location.protocol === "https:" ? "; Secure" : "";
  document.cookie = `${APP_LOCALE_COOKIE}=${locale}; Max-Age=${APP_LOCALE_COOKIE_MAX_AGE}; Path=/; SameSite=Lax${secure}`;
}
